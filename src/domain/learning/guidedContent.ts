function order(id: string, cue: string, ko: string, ja: string, answer: string[], hintKo: string, hintJa: string): DailyLessonItem {
  const quiz: LessonQuiz = { id, mode: "order", cue, prompt: { ko, ja }, choices: [...answer].reverse(), answer, hint: { ko: hintKo, ja: hintJa } };
  return { characterId: id, kind: "new", quiz };
}

