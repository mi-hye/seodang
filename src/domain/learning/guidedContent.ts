import type { DailyLessonItem, LessonQuiz } from "../../types/app-state";
import { BASIC_HIRAGANA, BASIC_KATAKANA, KANA_KOREAN_READINGS, KANA_ROMAJI, getKanaCharacterId } from "../../data/kanaCatalog.ts";

function choice(id: string, cue: string, ko: string, ja: string, choices: string[], answer: string, hintKo: string, hintJa: string): DailyLessonItem {
  return { characterId: id, kind: "new", quiz: { id, mode: "choice", cue, prompt: { ko, ja }, choices, answer: [answer], hint: { ko: hintKo, ja: hintJa } } };
}

export const KANA_QUESTIONS: DailyLessonItem[] = [BASIC_HIRAGANA, BASIC_KATAKANA].flatMap((script, scriptIndex) => {
  const letters = [...script];
  return letters.map((literal, index) => ({
    ...choice(getKanaCharacterId(literal), KANA_KOREAN_READINGS[index] + " · " + KANA_ROMAJI[index],
      "이 소리로 읽는 글자를 찾아요", "ローマ字の読み方に合う文字を選ぼう",
      [literal, letters[(index + 1) % letters.length], letters[(index + 4) % letters.length]], literal,
      literal + " → " + KANA_KOREAN_READINGS[index] + " (" + KANA_ROMAJI[index] + "). 모양을 보고 다시 골라봐요.",
      literal + " → " + KANA_ROMAJI[index] + "。形を見て、もう一度選ぼう。"),
    categoryKey: scriptIndex === 0 ? "kana_hiragana" : "kana_katakana",
  }));
});

