#!/usr/bin/env node

import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const rootDir = process.cwd();
const outputPath = path.join(
  rootDir,
  "supabase/functions/kanji-catalog/catalog-data.ts"
);

const categoryGroups = await readJson(
  path.join(rootDir, "data/seeds/kanji-category-groups.json")
);
const categories = await readJson(path.join(rootDir, "data/seeds/kanji-categories.json"));
const characterCategories = await readJson(
  path.join(rootDir, "data/generated/kanji-character-categories.generated.json")
);
const kanjiMetadata = await readJson(
  path.join(rootDir, "data/generated/kanji-metadata.generated.json")
);

const characterMap = new Map(kanjiMetadata.map((character) => [character.id, character]));
const practicalCharacterIds = new Set(
  kanjiMetadata
    .filter((character) => isPracticalCharacter(character))
    .map((character) => character.id)
);
const allCategoryGroups = uniqueRows(
  [...categoryGroups, buildRadicalCategoryGroup()],
  (group) => group.id
);
const allCategories = uniqueRows(
  [...categories, ...buildRadicalCategories()],
  (category) => category.id
);
const categoryIds = new Set(allCategories.map((category) => category.id));
const characterIdsByCategoryId = new Map();

for (const mapping of characterCategories) {
  if (
    !categoryIds.has(mapping.categoryId) ||
    !practicalCharacterIds.has(mapping.characterId) ||
    !characterMap.has(mapping.characterId)
  ) {
    continue;
  }

  const current = characterIdsByCategoryId.get(mapping.categoryId) ?? [];
  current.push(mapping.characterId);
  characterIdsByCategoryId.set(mapping.categoryId, current);
}

const categoryIdToKey = new Map(
  allCategories.map((category) => [category.id, category.categoryKey])
);
const characterIdsByCategoryKey = Object.fromEntries(
  Array.from(characterIdsByCategoryId.entries())
    .map(([categoryId, characterIds]) => [
      categoryIdToKey.get(categoryId),
      [...new Set(characterIds)],
    ])
    .filter(([categoryKey]) => Boolean(categoryKey))
    .sort(([left], [right]) => String(left).localeCompare(String(right)))
);

await mkdir(path.dirname(outputPath), { recursive: true });
await writeFile(
  outputPath,
  [
    "// Generated by scripts/build-kanji-catalog-edge-index.mjs",
    "// Do not edit by hand.",
    "",
    `export const catalogCategoryGroups = ${JSON.stringify(
      allCategoryGroups.map(mapCategoryGroupRow),
      null,
      2
    )} as const;`,
    "",
    `export const catalogCategories = ${JSON.stringify(
      allCategories.map(mapCategoryRow),
      null,
      2
    )} as const;`,
    "",
    `export const catalogCharacterIdsByCategoryKey = ${JSON.stringify(
      characterIdsByCategoryKey,
      null,
      2
    )} as const;`,
    "",
  ].join("\n"),
  "utf8"
);

console.log(
  `Wrote ${Object.keys(characterIdsByCategoryKey).length} indexed categories to ${path.relative(
    rootDir,
    outputPath
  )}.`
);

function isPracticalCharacter(character) {
  return Boolean(
    character.isJoyo ||
      character.jlptLevel ||
      character.japaneseGrade != null ||
      character.japaneseSchoolLevel
  );
}

function mapCategoryGroupRow(group) {
  return {
    id: group.id,
    group_key: group.groupKey,
    label_ko: group.labelKo,
    label_ja: group.labelJa,
    description_ko: group.descriptionKo ?? null,
    description_ja: group.descriptionJa ?? null,
    sort_order: group.sortOrder ?? 0,
  };
}

function mapCategoryRow(category) {
  return {
    id: category.id,
    group_id: category.groupId,
    category_key: category.categoryKey,
    label_ko: category.labelKo,
    label_ja: category.labelJa,
    description_ko: category.descriptionKo ?? null,
    description_ja: category.descriptionJa ?? null,
    sort_order: category.sortOrder ?? 0,
    metadata: category.metadata ?? {},
  };
}

function buildRadicalCategoryGroup() {
  return {
    id: "group_radical",
    groupKey: "radical",
    labelKo: "부수별",
    labelJa: "部首別",
    descriptionKo: "부수 기준으로 한자를 나눠 보는 분류",
    descriptionJa: "部首を基準に漢字を見る分類",
    sortOrder: 5,
    isActive: true,
  };
}

function buildRadicalCategories() {
  return Array.from({ length: 214 }, (_, index) => {
    const radicalNumber = index + 1;
    const radicalSymbol = toKangxiRadicalSymbol(radicalNumber);

    return {
      id: `cat_radical_${String(radicalNumber).padStart(3, "0")}`,
      groupId: "group_radical",
      categoryKey: `radical_${String(radicalNumber).padStart(3, "0")}`,
      labelKo: `${radicalNumber}부 ${radicalSymbol}`,
      labelJa: `${radicalNumber}部 ${radicalSymbol}`,
      descriptionKo: `${radicalNumber}부 ${radicalSymbol}에 속한 한자`,
      descriptionJa: `${radicalNumber}部 ${radicalSymbol} に属する漢字`,
      sortOrder: radicalNumber,
      isActive: true,
      metadata: {
        visibleLocales: ["ko", "ja"],
        radicalNumber,
        radicalSymbol,
      },
    };
  });
}

function toKangxiRadicalSymbol(radicalNumber) {
  if (!Number.isInteger(radicalNumber) || radicalNumber < 1 || radicalNumber > 214) {
    return null;
  }

  return String.fromCodePoint(0x2f00 + radicalNumber - 1);
}

function uniqueRows(rows, keyFn) {
  const seen = new Set();

  return rows.filter((row) => {
    const key = keyFn(row);
    if (seen.has(key)) {
      return false;
    }
    seen.add(key);
    return true;
  });
}

async function readJson(filePath) {
  const raw = await readFile(filePath, "utf8");
  return JSON.parse(raw);
}
