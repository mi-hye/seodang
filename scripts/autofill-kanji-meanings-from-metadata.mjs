function normalizeReadings(values) {
  if (!Array.isArray(values)) {
    return [];
  }

  return values
    .map((value) =>
      typeof value === "string"
        ? value.replace(/\./g, "").replace(/-$/g, "").trim()
        : null
    )
    .filter((value) => value && value.length > 0);
}

function unique() {
  const seen = new Set();
  return (value) => {
    if (seen.has(value)) {
      return false;
    }
    seen.add(value);
    return true;
  };
}
