function parseArgs(args) {
  const options = {
    input: defaultInputPath,
    metadata: defaultMetadataPath,
  };

  for (let index = 0; index < args.length; index += 1) {
    const value = args[index];
    if (value === "--input") {
      options.input = path.resolve(process.cwd(), args[index + 1] ?? defaultInputPath);
      index += 1;
      continue;
    }
    if (value === "--metadata") {
      options.metadata = path.resolve(
        process.cwd(),
        args[index + 1] ?? defaultMetadataPath
      );
      index += 1;
    }
  }

  return options;
}

async function readJson(filePath) {
  const raw = await fs.readFile(filePath, "utf8");
  return JSON.parse(raw);
}

function normalizeText(value) {
  if (typeof value !== "string") {
    return null;
  }
  const normalized = value.replace(/\s+/g, " ").trim();
  return normalized.length > 0 ? normalized : null;
}

function buildMeaningJa(metadata) {
  const kunyomi = normalizeReadings(metadata.kunyomi);
  const onyomi = normalizeReadings(metadata.onyomi);

  const primary = kunyomi.length > 0 ? kunyomi : onyomi;
  const secondary = kunyomi.length > 0 && onyomi.length > 0 ? onyomi : [];
  const merged = [...primary, ...secondary].filter(unique());

  if (merged.length === 0) {
    return null;
  }

  return merged.slice(0, 4).join("、");
}

function buildMeaningKo(metadata) {
  const meanings = Array.isArray(metadata?.metadata?.meaningEn)
    ? metadata.metadata.meaningEn
    : [];

  const mapped = meanings
    .flatMap((value) => mapEnglishMeaningToKo(value))
    .filter(unique());

  if (mapped.length === 0) {
    return null;
  }

  return mapped.slice(0, 4).join(", ");
}

